/** AI 용어 정리 화면의 내용. 용어를 추가하거나 상태가 바뀌면 여기만 고친다. */
export type TermStatus = 'doing' | 'next' | 'idea'

export const statusLabel: Record<TermStatus, string> = {
  doing: '진행 중',
  next: '다음',
  idea: '나중에',
}

export interface Term {
  name: string
  /** 먼저 알아야 할 핵심 용어. 화면에서 이름 앞에 ★ 를 붙인다 */
  core?: boolean
  en?: string
  /** 한 줄 뜻 */
  what: string
  /** 왜 필요한가: 이게 없으면 어떤 문제가 생기나 */
  why: string
  /** 해든 카페 안내 챗봇으로 설명한 한 줄 예시. 화면에서는 "쉬운 예시"로 보인다(코드 예제는 aiDemos.ts) */
  example: string
  /** 카페 설명과 세부가 다를 때, 이 노트 프로젝트에서 실제로 한 것(또는 할 것). 화면에서는 "프로젝트에서는"으로 보인다 */
  project?: string
  /** 알아 둘 점(선택) */
  note?: string
  status: TermStatus
}

export interface TermGroup {
  id: string
  title: string
  intro: string
  terms: Term[]
}

